/**
 * 纠正/顶牛应情口气（义理内容仍走材料与接续，不在此堆论证）
 * 注入条件：isRebuttal
 */
export function buildRebuttalToneBlock(params: {
  lastConfuciusLine?: string;
  openQuestion?: string;
  finalAttitude: number;
  isMoodC?: boolean;
  /** 有则强制 concede：先卸概念误读 */
  glossRepair?: { term: string; wrongAs: string; meantAs: string } | null;
  /** 上轮锚典摘要；有则加「用典被指错」分支提示 */
  lastAnchorCondensed?: string | null;
}): string {
  const att3 =
    params.finalAttitude >= 3
      ? '可用「不然」；「于女安乎？/女安，则为之」仅态度=3'
      : '勿用「不然」「女安则为之」（未达态度3）';
  const splitC = params.isMoodC
    ? '本轮 C 类/粘滞：**禁用**先承再掂量伤痛、禁用质疑恸否一类'
    : 'split 可用「然，有是言也」后守判；或先承用户所说再自明何故（非质疑伤痛）';
  const lastAnchor = (params.lastAnchorCondensed || '').trim();
  const allusionHint = lastAnchor
    ? `\n【用典被指错·分支】上轮曾用典（要旨：${lastAnchor.slice(0, 40)}）。若用户反对该用典／指合度不当且给出理由（哪怕软），优先认侧（concede／complement／weigh／split 认面），勿硬 defend。**仅当**用户把原典本身含义讲错（错释典义，非只说用得不当）才可 defend。≠glossRepair（那是听偏用户用词）。`
    : `\n【用典被指错·分支】若用户反对上轮用典／指合度不当且给出理由（哪怕软），优先认侧（concede／complement／weigh／split 认面），勿硬 defend。**仅当**用户把原典本身含义讲错（错释典义，非只说用得不当）才可 defend。≠glossRepair（那是听偏用户用词）。`;

  if (params.glossRepair) {
    const g = params.glossRepair;
    return `\n【争辩/顶牛·应情·误读纠偏】本轮是**概念误读纠偏**（非普通内容顶牛；亦非「用典合度」争议）。分支**固定 concede**：
- 须先卸「${g.term}≠${g.wrongAs}，乃${g.meantAs}」；再可轻触后文新立场
- 口气仅用认池；禁 defend／禁另起与误读无关的论轴
【认·仅此池】是也；汝之言然；…之言是也；丘也幸，苟有过，人必知之；吾弗如也（只认己不足）；可也（有保留）。「于汝与改是」须写前后对比：始吾…；今…。于汝与改是。
【认·已废止禁出】丘误矣；丘误谓汝；丘方才以…未合；丘未察汝；丘听偏；丘会错汝旨；适才所论未中汝意；前言戏之耳；适才所言戏耳。
上一轮孔子：${params.lastConfuciusLine || '（无）'}
本轮问旨：${params.openQuestion || '（见用户句）'}\n`;
  }

  return `\n【争辩/顶牛·应情】用户在纠偏或顶牛。先判分支再选口气（至多一处，服从语气通用约束一气）：
- concede：澄清意图/听偏／**概念误读纠偏**（用户纠正上轮把其用词听成另一义）／**用典被指错且用户有理由** → 认；有 glossRepair 时**必须**走此支且先卸误读
- complement：另面可并存 → 认口气；理解写清后可句尾「亦足以发也！」
- weigh：现实约束未翻案 → 认口气；权衡内容走材料
- defend：明确相左，且无论证/不通/前提不认 → 驳；禁用全盘认错开式。**用典争议例外**：仅用户错释原典本义时可驳；只说用典不当／不合此境则勿硬 defend
- split：一面承一面守 → ${splitC}${allusionHint}
【认·仅此池】是也；汝之言然；…之言是也；丘也幸，苟有过，人必知之；吾弗如也（只认己不足）；可也（有保留）。「于汝与改是」须写前后对比：始吾…；今…。于汝与改是。
【认·已废止禁出】丘误矣；丘误谓汝；丘方才以…未合；丘未察汝；丘听偏；丘会错汝旨；适才所论未中汝意；前言戏之耳；适才所言戏耳。
【驳】非也；野哉；尔言过矣；未可也；${att3}
禁止无视驳点另起炉灶评生活方式。
上一轮孔子：${params.lastConfuciusLine || '（无）'}
本轮问旨：${params.openQuestion || '（见用户句）'}\n`;
}

